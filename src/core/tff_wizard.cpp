std::string trim(const std::string& s) {
    auto start = s.find_first_not_of(" \t\r\n");
    if (start == std::string::npos)
        return "";
    auto end = s.find_last_not_of(" \t\r\n");
    return s.substr(start, end - start + 1);
}

std::string toLower(const std::string& s) {
    std::string res = s;
    std::transform(res.begin(), res.end(), res.begin(),
                   [](unsigned char c) { return std::tolower(c); });
    return res;
}

bool askYesNo(std::istream& in, std::ostream& out, const std::string& prompt, bool default_val) {
    out << prompt << (default_val ? " [Y/n]: " : " [y/N]: ");
    std::string line;
    if (!std::getline(in, line)) {
        return default_val;
    }
    std::string trimmed = toLower(trim(line));
    if (trimmed.empty()) {
        return default_val;
    }
    if (trimmed == "y" || trimmed == "yes" || trimmed == "1" || trimmed == "true") {
        return true;
    }
    if (trimmed == "n" || trimmed == "no" || trimmed == "0" || trimmed == "false") {
        return false;
    }
    return default_val;
}

